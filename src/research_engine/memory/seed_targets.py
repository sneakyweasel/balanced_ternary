def dump_board(path=None, memory=None, corpus=None) -> Path:
    from research_engine.diagnosis.corpus import ResearchCorpus
    from research_engine.memory.board import assemble_board
    from research_engine.memory.store import ResearchMemory

    store = memory if memory is not None else ResearchMemory.load_historical()
    session = corpus if corpus is not None else ResearchCorpus(
        tuple(item.diagnosis for item in store.experiments)
    )
    board = assemble_board(store, session)
    target = Path(path) if path is not None else BOARD_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    import json

    target.write_text(json.dumps(board.as_dict(), indent=2) + "\n", encoding="utf-8")
    return target


def load_board(path=None) -> TargetBoard:
    import json

    target = Path(path) if path is not None else BOARD_PATH
    return TargetBoard.from_dict(json.loads(target.read_text(encoding="utf-8")))
