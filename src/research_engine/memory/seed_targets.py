def _ev_placeholder(reason: str) -> ScoredAxis:
    return ScoredAxis(value=0.0, reason=reason)


def _blind(
    spec_name: str,
    *,
    dimension: int,
    allowed_definition: str,
    state_space: str,
    observation: str,
    initial_conditions: tuple[str, ...],
    forbidden_hints: tuple[str, ...],
    explicit_controls: str = "singleton dummy control",
    computational_budget: str = "at most 16 planner steps / 32 residual states",
    skip_attacks: tuple[str, ...] = (),
    max_states: int | None = 32,
    max_steps: int | None = 16,
) -> BlindPacket:
    return BlindPacket(
        spec_name=spec_name,
        dimension=dimension,
        skip_attacks=skip_attacks,
        max_states=max_states,
        max_steps=max_steps,
        allowed_definition=allowed_definition,
        state_space=state_space,
        observation=observation,
        initial_conditions=initial_conditions,
        explicit_controls=explicit_controls,
        computational_budget=computational_budget,
        forbidden_hints=forbidden_hints,
        post_run_reconciliation="",
        lean_targets=(),
    )


